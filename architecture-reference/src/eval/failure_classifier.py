"""【B 架构重构】Eval Failure 与 Trace Span 的稳定责任分类。"""
from enum import Enum


class FailureKind(str,Enum):
    ROUTING_FAILURE="ROUTING_FAILURE"
    SKILL_SELECTION_FAILURE="SKILL_SELECTION_FAILURE"
    CONTEXT_FAILURE="CONTEXT_FAILURE"
    MODEL_DECISION_FAILURE="MODEL_DECISION_FAILURE"
    TOOL_SELECTION_FAILURE="TOOL_SELECTION_FAILURE"
    TOOL_ARGUMENT_FAILURE="TOOL_ARGUMENT_FAILURE"
    TOOL_EXECUTION_FAILURE="TOOL_EXECUTION_FAILURE"
    RETRIEVAL_FAILURE="RETRIEVAL_FAILURE"
    RERANK_FAILURE="RERANK_FAILURE"
    EVIDENCE_FAILURE="EVIDENCE_FAILURE"
    COMPLETION_FAILURE="COMPLETION_FAILURE"
    PROVIDER_FAILURE="PROVIDER_FAILURE"
    INFRA_FAILURE="INFRA_FAILURE"
    BUSINESS_FAILURE="BUSINESS_FAILURE"
    MODEL_FAILURE="MODEL_DECISION_FAILURE"
    TOOL_FAILURE="TOOL_EXECUTION_FAILURE"
    HARNESS_FAILURE="COMPLETION_FAILURE"


SPAN_TO_FAILURE={
    "ROUTING":FailureKind.ROUTING_FAILURE,"SKILL_LOAD":FailureKind.SKILL_SELECTION_FAILURE,
    "CONTEXT_BUILD":FailureKind.CONTEXT_FAILURE,"MODEL_CALL":FailureKind.PROVIDER_FAILURE,
    "DECISION_VALIDATION":FailureKind.MODEL_DECISION_FAILURE,"TOOL_CALL":FailureKind.TOOL_SELECTION_FAILURE,
    "TOOL_RESULT":FailureKind.TOOL_EXECUTION_FAILURE,"COMPLETION":FailureKind.COMPLETION_FAILURE,
    "FINAL_ANSWER":FailureKind.EVIDENCE_FAILURE,
}


class FailureClassifier:
    def classify(self,*,span_type=None,error_code=None,infra=False):
        if infra: return FailureKind.INFRA_FAILURE
        code=(error_code or "").upper()
        if "EVIDENCE" in code: return FailureKind.EVIDENCE_FAILURE
        if "ARGUMENT" in code or "GROUNDING" in code: return FailureKind.TOOL_ARGUMENT_FAILURE
        if "RETRIEV" in code: return FailureKind.RETRIEVAL_FAILURE
        if "RERANK" in code: return FailureKind.RERANK_FAILURE
        return SPAN_TO_FAILURE.get(getattr(span_type,"value",span_type),FailureKind.BUSINESS_FAILURE)
